"""Answer every question in questions.txt and write results/answers.md and results/lms_answers.txt."""

import sys
import time

from ask import answer_question, format_result
from config import BASE_DIR, quiet_libraries

DELAY_SECONDS = 2.0


def read_questions() -> list[str]:
    lines = (BASE_DIR / "questions.txt").read_text(encoding="utf-8").splitlines()
    return [line.strip() for line in lines if line.strip() and not line.strip().startswith("#")]


def page_reference(result) -> str:
    if not result.found:
        return "No reference (not in the document)"
    parts = [f"page {s['page']}" + (f", section \"{s['section']}\"" if s.get("section") else "") for s in result.sources]
    return f"{result.sources[0]['filename']}, " + "; ".join(parts)


def main() -> int:
    quiet_libraries()
    questions = read_questions()
    md = ["# Answers", "", "Generated by `python run_questions.py` from `questions.txt`.", ""]
    lms = []
    for number, question in enumerate(questions, 1):
        result = answer_question(question)
        print(format_result(question, result) + "\n")
        md += [f"### {number}. {question}", "", f"**Answer:** {result.answer}", "", f"**Reference:** {page_reference(result)}", ""]
        md += [f"> Page {s['page']}: \"{s['excerpt']}\"" + "\n" for s in result.sources]
        lms += [f"{number}. Question: {question}", f"   Answer: {result.answer}", f"   Reference: {page_reference(result)}", ""]
        time.sleep(DELAY_SECONDS)

    results_dir = BASE_DIR / "results"
    results_dir.mkdir(exist_ok=True)
    (results_dir / "answers.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (results_dir / "lms_answers.txt").write_text("\n".join(lms), encoding="utf-8")
    print(f"Wrote {results_dir / 'answers.md'} and {results_dir / 'lms_answers.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
